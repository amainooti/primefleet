import { mkdir, writeFile, readFile, rm } from "fs/promises";
import path from "path";
import crypto from "crypto";

// Portal documents (insurance certificates, lease agreements, …) are stored
// OUTSIDE /public so they are only reachable through the download route.
// On the VPS mount PORTAL_UPLOAD_DIR (or ./storage) as a persistent volume.
const ROOT = process.env.PORTAL_UPLOAD_DIR
  ? path.resolve(process.env.PORTAL_UPLOAD_DIR)
  : path.join(process.cwd(), "storage", "portal");

export const MAX_FILE_SIZE = 10 * 1024 * 1024; // 10MB each
export const MAX_FILES_PER_REQUEST = 4; // keeps a single request under the body limit
export const MAX_FILES_PER_PORTAL = 25;

export class PortalStorageError extends Error {}

type Kind = { ext: string; mime: string };

// Detect by magic bytes — never trust the browser-supplied MIME type.
function sniff(buf: Buffer): Kind | null {
  if (buf.length < 12) return null;
  if (buf.subarray(0, 5).toString("latin1") === "%PDF-")
    return { ext: "pdf", mime: "application/pdf" };
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff)
    return { ext: "jpg", mime: "image/jpeg" };
  if (buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])))
    return { ext: "png", mime: "image/png" };
  if (
    buf.subarray(0, 4).toString("latin1") === "RIFF" &&
    buf.subarray(8, 12).toString("latin1") === "WEBP"
  )
    return { ext: "webp", mime: "image/webp" };
  if (buf[0] === 0x50 && buf[1] === 0x4b && buf[2] === 0x03 && buf[3] === 0x04)
    return {
      ext: "docx",
      mime: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
    };
  return null;
}

export const ACCEPT_ATTR = ".pdf,.jpg,.jpeg,.png,.webp,.docx";

function safeName(name: string) {
  const base = name.replace(/[\\/]/g, "_").replace(/[^\w.\- ()]/g, "_").trim();
  return base.slice(0, 120) || "document";
}

export async function savePortalFile(file: File) {
  if (file.size > MAX_FILE_SIZE) {
    throw new PortalStorageError(`"${file.name}" exceeds the 10MB limit.`);
  }
  const buffer = Buffer.from(await file.arrayBuffer());
  const kind = sniff(buffer);
  if (!kind) {
    throw new PortalStorageError(
      `"${file.name}" is not a supported file type (PDF, JPG, PNG, WEBP or DOCX).`
    );
  }
  await mkdir(ROOT, { recursive: true });
  const storedName = `${crypto.randomUUID()}.${kind.ext}`;
  await writeFile(path.join(ROOT, storedName), buffer);
  return {
    storedName,
    mimeType: kind.mime,
    size: buffer.length,
    fileName: safeName(file.name),
  };
}

function resolveStored(storedName: string) {
  // storedName is generated by us, but guard against traversal regardless.
  if (!/^[0-9a-f-]{36}\.(pdf|jpg|png|webp|docx)$/.test(storedName)) {
    throw new PortalStorageError("Invalid file reference.");
  }
  return path.join(ROOT, storedName);
}

export async function readPortalFile(storedName: string) {
  return readFile(resolveStored(storedName));
}

export async function deletePortalFile(storedName: string) {
  await rm(resolveStored(storedName), { force: true });
}
